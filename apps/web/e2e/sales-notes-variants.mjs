import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {fixture} from '../../api/scripts/sales-notes-test-helpers.mjs';
const {c,customer,reg,item}=await fixture('Physical, commercial debit and LUT note UI');
const uom=(await c.req('GET','/uoms')).find(x=>x.code==='NOS');
await c.req('POST','/hsn-codes',{code:'7601',kind:'hsn',description:'Browser return metal',gstRate:'18',effectiveFrom:'2025-04-01'},201);
const good=await c.req('POST','/items',{code:'GOOD',name:'Physical returned goods',type:'raw_material',stockUomId:uom.id,hsnCode:'7601'},201);
const wh=await c.req('POST','/warehouses',{code:'RET',name:'Browser return destination',type:'stores'},201);
const receipt=await c.req('POST','/stock-entries',{purpose:'receipt',postingDate:c.settings.cutoverDate,lines:[{itemId:good.id,qty:'2',toWarehouseId:wh.id,rate:'10'}]},201);
await c.req('POST',`/stock-entries/${receipt.id}/submit`,{},201);
let inv=await c.req('POST','/sales-invoices',{customerId:customer.id,gstRegistrationId:reg.id,invoiceDate:c.settings.cutoverDate,placeOfSupplyStateCode:'27',lines:[{itemId:good.id,qty:'2',rate:'100',gstRate:'18',warehouseId:wh.id}]},201);
await c.req('POST',`/sales-invoices/${inv.id}/submit`,{},201);
const exp=await c.req('POST','/parties',{code:'EXP',name:'Browser LUT customer',isCustomer:true,gstTreatment:'overseas'},201);
await c.req('PATCH',`/gst-registrations/${reg.id}`,{lutArn:'AD270326001234X',lutValidFrom:'2026-04-01',lutValidTo:'2027-03-31'});
let foreign=await c.req('POST','/sales-invoices',{customerId:exp.id,gstRegistrationId:reg.id,invoiceDate:c.settings.cutoverDate,supplyType:'export_under_lut',currency:'USD',exchangeRate:'80',placeOfSupplyStateCode:'96',lines:[{itemId:item.id,qty:'1',rate:'100',gstRate:'0'}]},201);
await c.req('POST',`/sales-invoices/${foreign.id}/submit`,{},201);
const B=process.env.WEB_URL??'http://localhost:3000';
const browser=await chromium.launch(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{}),ctx=await browser.newContext();
await ctx.addCookies(c.cookie.split('; ').map(cookie=>{const i=cookie.indexOf('=');return {name:cookie.slice(0,i),value:cookie.slice(i+1),url:B};}));
await ctx.addInitScript(({tenantId,entityId})=>{localStorage.setItem('fos.tenant',tenantId);localStorage.setItem(`fos.entity.${tenantId}`,entityId);},{tenantId:c.tenantId,entityId:c.entityId});
const page=await ctx.newPage(),errors=[];page.setDefaultTimeout(15000);page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto(`${B}/app/selling/notes/new?invoiceId=${inv.id}`);
 await page.getByLabel('Reason').fill('Return one original dispatched item');
 await page.getByLabel('Adjustment mode').selectOption('quantity');
 await page.getByLabel('Credited quantity').fill('1');
 await page.getByLabel('Returned quantity').fill('1');
 await page.getByLabel('Return warehouse').selectOption(wh.id);
 await page.getByLabel('Confirm GST credit eligibility').check();
 await page.getByText('Original stock cost restored: INR 10.000000',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Submit note',exact:true}).click();
 await page.waitForURL('**/selling/notes/*');
 await page.getByRole('link',{name:'Return stock movement',exact:true}).waitFor();
 let noteId=page.url().split('/').at(-1);
 assert.equal((await c.req('GET',`/sales-notes/${noteId}`)).grandTotal,'118.000000');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/sales-notes-physical-mobile.png',fullPage:true});
 await page.goto(`${B}/app/selling/notes/new?invoiceId=${inv.id}&kind=debit`);
 await page.getByLabel('Reason').fill('Add agreed commercial service charge');
 await page.getByLabel('Tax treatment').selectOption('commercial');
 await page.getByLabel('Taxable adjustment').fill('10');
 await page.getByText('Total: INR 10.00',{exact:true}).waitFor();
 assert.equal(await page.getByLabel('Returned quantity').count(),0);
 await page.getByRole('button',{name:'Submit note',exact:true}).click();
 await page.waitForURL('**/selling/notes/*');
 await page.getByText(/Note bill remaining: INR 10\.000000/).waitFor();
 noteId=page.url().split('/').at(-1);
 await page.goto(`${B}/app/selling/notes/${noteId}/print`);
 await page.getByText('Commercial-only note · No GST adjustment claimed',{exact:true}).waitFor();
 await page.goto(`${B}/app/selling/notes/new?invoiceId=${foreign.id}`);
 await page.getByLabel('Reason').fill('Correct original exported service value');
 await page.getByLabel('Taxable adjustment').fill('20');
 await page.getByLabel('Confirm GST credit eligibility').check();
 await page.getByText('Total: USD 20.00',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Submit note',exact:true}).click();
 await page.waitForURL('**/selling/notes/*');
 await page.getByText(/Customer credit remaining: USD 0\.000000/).waitFor();
 noteId=page.url().split('/').at(-1);
 await page.goto(`${B}/app/selling/notes/${noteId}/print`);
 await page.getByText(/LUT ARN AD270326001234X/).waitFor();
 assert.deepEqual(errors,[]);
 console.log('PASS physical return, commercial debit, mobile and foreign LUT note UI');
}catch(e){await page.screenshot({path:'/tmp/sales-notes-variants-failure.png',fullPage:true});throw e;}finally{await browser.close();}
