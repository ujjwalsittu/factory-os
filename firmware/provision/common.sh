# Shared by the provisioning scripts (decision 064). Sourced, not run.
# Everything lives under EDGE_DIR (default /etc/factoryos-edge):
#   provision.env   settings (tenant, plant, edge host, Wi-Fi) — root only, it holds the Wi-Fi password
#   pki/            the plant CA and every certificate issued — root only
#   mosquitto/      what the broker container mounts as /mosquitto/config
#   agent/          the edge agent's certificates (MQTT client, firmware server)
set -euo pipefail
umask 077

EDGE_DIR="${EDGE_DIR:-/etc/factoryos-edge}"
PKI="$EDGE_DIR/pki"
MQ="$EDGE_DIR/mosquitto"
AGENT="$EDGE_DIR/agent"
# shellcheck disable=SC1091
if [ -f "$EDGE_DIR/provision.env" ]; then set -a; . "$EDGE_DIR/provision.env"; set +a; fi
MOSQUITTO_RELOAD="${MOSQUITTO_RELOAD:-docker kill --signal=HUP factoryos-mosquitto}"
MOSQUITTO_RESTART="${MOSQUITTO_RESTART:-docker restart factoryos-mosquitto}"
# The uid the broker runs as inside the eclipse-mosquitto image; it must read its key and the CRL.
MOSQUITTO_UID="${MOSQUITTO_UID:-1883}"

die() { echo "error: $*" >&2; exit 1; }
need() { for v in "$@"; do [ -n "${!v:-}" ] || die "set $v in $EDGE_DIR/provision.env"; done; }
code_ok() { [[ "$1" =~ ^[A-Za-z0-9._-]{2,40}$ ]] || die "bad code '$1': letters, digits, dot, dash or underscore"; }

# The broker's view of who may do what: the edge agent everything in this plant, each tap with a valid certificate its
# own state and status (write) and its config and the plant's firmware announcement (read). Rebuilt from the CA's
# index so a revoked tap disappears.
write_acl() {
  local base="factoryos/$TENANT/$PLANT"
  {
    echo "# Generated by firmware/provision; edits are overwritten."
    echo "user edge-agent"
    echo "topic readwrite $base/#"
    awk -F'\t' '$1 == "V" && $6 ~ /\/OU=FactoryOS tap\// { sub(/.*\/CN=/, "", $6); print $6 }' "$PKI/index.txt" | sort -u | while read -r d; do
      echo
      echo "user $d"
      echo "topic write $base/$d/state"
      echo "topic write $base/$d/status"
      echo "topic read $base/$d/config"
      echo "topic read $base/ota"
    done
  } > "$MQ/acl.new"
  mv "$MQ/acl.new" "$MQ/acl"
  broker_owns "$MQ/acl"
}

write_crl() {
  openssl ca -config "$PKI/openssl.cnf" -gencrl -out "$PKI/crl.pem" 2>/dev/null
  cp "$PKI/crl.pem" "$MQ/crl.pem"
  broker_owns "$MQ/crl.pem"
}

broker_owns() { chown "$MOSQUITTO_UID:$MOSQUITTO_UID" "$@" 2>/dev/null || true; chmod 600 "$@"; }
