#!/usr/bin/env bash
# Creates the plant CA once on the edge PC (decision 064), then the certificates the plant runs on:
#   - the broker and firmware server certificate (CN = EDGE_HOST, plus localhost);
#   - the edge agent's MQTT client certificate (CN = edge-agent).
# It also writes the broker's config, ACL and empty CRL under $EDGE_DIR/mosquitto.
# The CA key (ECDSA P-256) never leaves $EDGE_DIR/pki, which only root can read.
# Usage (as root): firmware/provision/plant-ca.sh
here="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=common.sh
. "$here/common.sh"
need TENANT PLANT EDGE_HOST
code_ok "$PLANT"
[ -f "$PKI/ca.key" ] && die "the plant CA already exists in $PKI; it is created once"
mkdir -p "$PKI/issued" "$PKI/taps" "$MQ" "$AGENT"
chmod 700 "$PKI"

cat > "$PKI/openssl.cnf" <<CNF
[ ca ]
default_ca = plant

[ plant ]
dir = $PKI
database = \$dir/index.txt
new_certs_dir = \$dir/issued
certificate = \$dir/ca.crt
private_key = \$dir/ca.key
serial = \$dir/serial
crlnumber = \$dir/crlnumber
default_md = sha256
policy = anything
copy_extensions = none
# A stale CRL makes the broker refuse every tap, so it stays valid for ten years; revoking writes a new one.
default_crl_days = 3650
unique_subject = no

[ anything ]
organizationName = optional
organizationalUnitName = optional
commonName = supplied

[ client_cert ]
basicConstraints = critical, CA:FALSE
keyUsage = critical, digitalSignature
extendedKeyUsage = clientAuth
CNF
: > "$PKI/index.txt"
echo "unique_subject = no" > "$PKI/index.txt.attr"
openssl rand -hex 16 > "$PKI/serial"
echo 1000 > "$PKI/crlnumber"

echo "→ plant CA for $PLANT (ECDSA P-256, 20 years)"
openssl ecparam -name prime256v1 -genkey -noout -out "$PKI/ca.key"
openssl req -new -x509 -key "$PKI/ca.key" -sha256 -days 7305 -out "$PKI/ca.crt" \
  -subj "/O=FactoryOS/OU=Plant $PLANT/CN=FactoryOS plant CA $PLANT" \
  -addext "basicConstraints=critical,CA:TRUE,pathlen:0" -addext "keyUsage=critical,keyCertSign,cRLSign"

# The server certificate's names: the edge PC's host name, and localhost for the edge agent on the same machine.
cat > "$PKI/server-ext.cnf" <<EXT
[ server_cert ]
basicConstraints = critical, CA:FALSE
keyUsage = critical, digitalSignature
extendedKeyUsage = serverAuth
subjectAltName = DNS:$EDGE_HOST,DNS:localhost,IP:127.0.0.1${EDGE_IP:+,IP:$EDGE_IP}
EXT

# issue <name> <subject> <days> <openssl ca options…>: key and certificate under $PKI/issued/<name>.{key,crt}
issue() {
  local name="$1" subject="$2" days="$3"
  shift 3
  openssl ecparam -name prime256v1 -genkey -noout -out "$PKI/issued/$name.key"
  openssl req -new -key "$PKI/issued/$name.key" -subj "$subject" -out "$PKI/issued/$name.csr"
  openssl ca -batch -config "$PKI/openssl.cnf" "$@" -days "$days" -notext -in "$PKI/issued/$name.csr" -out "$PKI/issued/$name.crt" 2>/dev/null
  rm "$PKI/issued/$name.csr"
}
echo "→ broker and firmware server certificate for $EDGE_HOST"
issue server "/O=FactoryOS/OU=Plant $PLANT/CN=$EDGE_HOST" 1825 -extfile "$PKI/server-ext.cnf" -extensions server_cert
echo "→ edge agent client certificate"
issue edge-agent "/O=FactoryOS/OU=Plant $PLANT/CN=edge-agent" 1825 -extensions client_cert

cp "$PKI/ca.crt" "$MQ/ca.crt"
cp "$PKI/issued/server.crt" "$MQ/server.crt"
cp "$PKI/issued/server.key" "$MQ/server.key"
cp "$PKI/ca.crt" "$AGENT/ca.crt"
cp "$PKI/issued/edge-agent.crt" "$AGENT/mqtt-client.crt"
cp "$PKI/issued/edge-agent.key" "$AGENT/mqtt-client.key"
cp "$PKI/issued/server.crt" "$AGENT/ota-server.crt"
cp "$PKI/issued/server.key" "$AGENT/ota-server.key"

cat > "$MQ/mosquitto.conf" <<CONF
# Generated by firmware/provision/plant-ca.sh (decision 064). TLS with client certificates only; no anonymous access.
per_listener_settings false
allow_anonymous false
listener 8883
cafile /mosquitto/config/ca.crt
certfile /mosquitto/config/server.crt
keyfile /mosquitto/config/server.key
crlfile /mosquitto/config/crl.pem
require_certificate true
use_identity_as_username true
tls_version tlsv1.2
acl_file /mosquitto/config/acl
persistence true
persistence_location /mosquitto/data/
log_dest stdout
CONF
chmod 644 "$MQ/mosquitto.conf" "$MQ/ca.crt" "$MQ/server.crt"
broker_owns "$MQ/server.key"
write_crl
write_acl
echo "Plant CA ready. Broker config in $MQ, edge agent certificates in $AGENT."
